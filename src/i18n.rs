impl Strings {
    pub fn update_up_to_date(&self, version: &str) -> String {
        format!("{}{version}).", self.msg_update_up_to_date_prefix)
    }

    pub fn update_installed(&self, from: &str, to: &str, lang: Language) -> String {
        match lang {
            Language::De => format!("Aktualisiert von v{from} auf {to}. Die Anwendung startet neu."),
            Language::En => format!("Updated from v{from} to {to}. The application will now restart."),
            Language::Fr => format!("Mis à jour de la v{from} vers {to}. L'application va redémarrer."),
        }
    }
}

