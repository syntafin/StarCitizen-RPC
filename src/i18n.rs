#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn parses_explicit_languages() {
        assert_eq!(Language::from_config_str("de"), Language::De);
        assert_eq!(Language::from_config_str("DE-DE"), Language::De);
        assert_eq!(Language::from_config_str("en"), Language::En);
        assert_eq!(Language::from_config_str("fr"), Language::Fr);
        assert_eq!(Language::from_config_str("français"), Language::Fr);
    }

    #[test]
    fn exposes_distinct_strings_per_language() {
        assert_eq!(Language::De.strings().pu_in_verse, "Im Verse");
        assert_eq!(Language::En.strings().pu_in_verse, "In the Verse");
        assert_eq!(Language::Fr.strings().pu_in_verse, "Dans le Verse");
    }
}
