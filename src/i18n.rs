#[derive(Debug, Clone, Copy, PartialEq, Eq, Default)]
pub enum Language {
    De,
    #[default]
    En,
    Fr,
}

impl Language {
    pub fn from_config_str(raw: &str) -> Self {
        match raw.trim().to_ascii_lowercase().as_str() {
            "de" | "de-de" | "de-at" | "de-ch" | "deutsch" | "german" => Self::De,
            "en" | "en-us" | "en-gb" | "english" | "englisch" => Self::En,
            "fr" | "fr-fr" | "fr-ca" | "français" | "francais" | "french" => Self::Fr,
            _ => detect_system_language(),
        }
    }

    pub fn strings(self) -> &'static Strings {
        match self {
            Self::De => &DE,
            Self::En => &EN,
            Self::Fr => &FR,
        }
    }
}

#[cfg(target_os = "windows")]
pub fn detect_system_language() -> Language {
    use windows_sys::Win32::Globalization::GetUserDefaultUILanguage;

    let lang_id = unsafe { GetUserDefaultUILanguage() };
    let primary_lang = lang_id & 0x03FF;
    match primary_lang {
        0x07 => Language::De, // LANG_GERMAN
        0x0C => Language::Fr, // LANG_FRENCH
        _ => Language::En,
    }
}

#[cfg(not(target_os = "windows"))]
pub fn detect_system_language() -> Language {
    Language::En
}

